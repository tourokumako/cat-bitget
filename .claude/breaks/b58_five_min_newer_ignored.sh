#!/bin/bash
# EXPECT_RC: 1
# MEANS: その検査が落ちた（守りが働いた）
# b58 — 5分足を取り足したのに、正本の指し先が古いままの状態を作ると、番人が落ちるか
#
#   守っているもの＝設計書 iter="insp5-path-and-tidy-head-20260908" の完成の条件 #1。
#   何を守るか＝このプロジェクトは5分足を取り足すとき「新ファイルを別名で保存」する
#     （要件定義書 §8.2.1.1 の④）。指し先（observe_diag.py の BARS_CSV）が古いままだと、
#     番人は古いファイルの末を見て「覆っている」と言い、検査5 は新しいファイルで走って落ちる。
#     監査 cp31 が、その状態を実際に作って再現した（番人4件が全部 通るのに検査5 は止まった）。
#   壊し方＝data に、正本より後の末を持つ5分足の控えを置く（中身は2行の見本・終わったら消す）。
#   測るもの＝observe_diag.py --selftest-insp5（番人 T-m が、正本より後のファイルが在るかを見る）。
#   期待＝置くと T-m が落ちて 1 になる。
#
# ★時間について＝承認のときの打ち切りは 120秒。軽い口だけを走らせる。
#
# 限界（正直に書く）
#   ①控えは2行の見本＝値の正しさは見ていない（T-m が見るのは末の時刻だけ）
#   ②data の外に置かれたファイルは見つけられない（名前で見分けている）
#   ③このプログラム自身を書き換えれば無効にできる（承認のときに凍結される）

source "$(dirname "$0")/lib.sh"

OBS="$PR/observe_diag.py"
NEW_CSV="$SDK/data/BTCUSDT-5m-2021-04-01_2026-08-31_V9FULL_safe.csv"
if [ -f "$NEW_CSV" ]; then
    echo "❌ 置く先が既に在る: $NEW_CSV（b58 の前提が変わった）" >&2
    exit 98
fi
guard "$NEW_CSV"

printf 'timestamp,open,high,low,close,volume\n2026-08-31 23:50:00,1,1,1,1,1\n2026-08-31 23:55:00,1,1,1,1,1\n' > "$NEW_CSV"

measure python3 "$OBS" --selftest-insp5
finish
