# b86 — 候補を元データで絞る処理を壊すと、候補の出どころの検査が落ちるか
#   守っているもの＝完成の条件 条件12（候補の出どころ4つ）
#   期待＝自己テスト T40③-4 が落ちる（終了コード 1）。
#   ★壊す対象が見つからなければ止まる（黙って壊さない）。
source "$(dirname "$0")/lib.sh"

# ★2026-09-12＝壊し方を3回 作り直した。経緯を全部 残す（同じ失敗を繰り返さないため）。
#   測る相手＝T40③（候補の出どころ4つ）のどれか。
#   1回目＝法則 R5 の family を空にした。**法則ファイルの読み込みが「側が不正」で止まった**
#     ＝狙った検査の前に落ちた（走らせて確認）。
#   2回目＝「側」の欄も消した。**こんどは束が1本も組めず T30 が落ちた**
#     ＝やはり狙った検査ではない（走らせて確認）。
#   3回目＝元データで絞る行を消し、元データの外の指標（MMI）を出す形にした。
#     **これも効かない**＝MMI は設定ファイル（observe_config.json）に0件で、
#     パラメータの範囲が無いため、その手前の `fam not in ranges` で飛ばされる（走らせる前に確認）。
#   4回目＝元データで絞る行を「全部 飛ばす」に変えた。**これも効かなかった**（走らせて確認）
#     ＝候補が0件になるところまでは狙いどおりだが、`build_stage_candidates` は0件のとき
#     `SampleError` を投げる。＝T40③-4 の判定に**到達しない**（落ちたのは T24⑥）。
#     ★T40③-4「候補が0件」は、到達できない判定だった。
#   ★いまの形（5回目）＝元データで絞る **2行を消す**（絞りを無効にする）。
#     ＝法則 R1 が名指しした系統「構造・位置」の指標が全部 通る。
#     系統「構造・位置」は **60件**、段1 の元データの語は **11件**＝49件が元データの外。
#     ＝元データの外の指標が候補に出て、T40③-1 が落ちる。
#     ★候補は0件にならないので、例外で止まらず、T40③ の判定に到達する。
GEN="$PR/engine_tuner_gen.py"
