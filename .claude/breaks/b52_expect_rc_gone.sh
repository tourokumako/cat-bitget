#!/bin/bash
# EXPECT_RC: 1
# MEANS: その検査が落ちた（守りが働いた）
# b52 — 宣言を読む処理から「宣言が無ければ止める」枝を消すと、番人が落ちるか
#
#   守っているもの＝next_step §6 の159番（設計書 iter="break-expect-rc-20260908" の
#     完成の条件 #1）。監査 cp29 の §4-2 と §5-5。
#   何を守るか＝壊すプログラムの合格を「終了コードが 0 以外」で決めていたので、
#     b51（向きが裏返っている＝土台ゲートが通ったのが正しい成功）は、記録にも表示にも
#     反対の意味が残っていた。さらに、中で異常が起きた終了コード（lib.sh の 99＝
#     控えから戻せなかった）まで「止まった」に数えていた。
#     直した後＝壊すプログラムが自分で「期待する終了コードと、その意味」を宣言し、
#     走らせる道具がそれと照らす。**ファイルは在るのに宣言が無ければ止める。**
#     その枝が消えると、宣言を書き忘れた .sh が黙って通る＝仕組みの入口が開く。
#   壊し方＝expect_of の「止める枝」を2つとも消す（EXPECT_RC が無いとき・MEANS が無いとき）。
#          ★2026-09-08 に直した＝最初は EXPECT_RC の枝だけを消したが、MEANS の枝が残るので
#            番人 T9（宣言をまったく書いていない見本）は通ってしまい、b52 が rc=0 になった。
#            ＝「壊したのに落ちない」＝守りの本体を測れていなかった。承認のときに実測して分かった。
#   測るもの＝`run_breaks.py --selftest`（番人 T9 が この枝を試す）。
#   期待＝壊すと T9 が落ちて終了コードが 1 になる。
#
# ★時間について（b35 の事故の教訓）＝承認のときの打ち切りは 120秒。実測（2026-09-08）＝1秒未満。
#
# 限界（正直に書く）
#   ①壊すのは「止める枝」2つだけ（宣言を読む正規表現そのものを壊す形は、この1本では測れない）
#   ②番人のほかの枝は見ない（終了コードだけを見る）
#   ③宣言した値が正しいかは、この1本でも機械でも見ない（CC が実測から書き写す）
#   ④このプログラム自身を書き換えれば無効にできる（承認のときに凍結される）

source "$(dirname "$0")/lib.sh"

T="$ROOT/.claude/tools/run_breaks.py"
guard "$T"

python3 - "$T" <<'PYEOF'
import sys
p = sys.argv[1]
s = open(p, encoding='utf-8').read()
before = s
s = s.replace(
    '    if rc is None:\n'
    '        return None, "", f"宣言 # EXPECT_RC: がありません: {name}"\n'
    '    if not means:\n'
    '        return None, "", f"宣言 # MEANS: がありません: {name}"\n',
    '    if rc is None:\n'
    '        rc = 0\n'
    '    if not means:\n'
    '        means = ""\n',
    1)
if s == before:
    raise SystemExit("壊す対象の行が見つからない（b52 の前提が変わった）")
open(p, 'w', encoding='utf-8').write(s)
PYEOF

measure python3 "$T" --selftest
finish
